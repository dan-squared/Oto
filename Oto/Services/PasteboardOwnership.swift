import AppKit
import ApplicationServices
import Foundation
import os

/// Pasteboard-file logger: restore failure must never be silent (a failed
/// write after clearContents leaves the clipboard empty — the one case
/// where the prior clipboard is unrecoverable by design).
nonisolated private let log = Logger(subsystem: "app.Oto", category: "pasteboard")

/// Clipboard ownership for insertion (01 §5, 15:121).
///
/// The safety property is ownership, not delay: Oto writes a unique marker,
/// records the change count, and restores the previous snapshot only if the
/// marker and count still match. If the person copied anything meanwhile, we
/// leave their clipboard alone and the transcript stays recoverable.
struct PasteboardReceipt: Equatable, Sendable {
    nonisolated static let markerType = NSPasteboard.PasteboardType("com.oto.session-marker")
    /// Standard NSPasteboard.org marker telling clipboard managers (Raycast,
    /// Paste, Maccy, Alfred) to ignore transient pasteboard traffic.
    nonisolated static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    /// Standard NSPasteboard.org marker for auto-generated clipboard writes.
    nonisolated static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    let marker: String
    let changeCount: Int

    nonisolated func stillOwned(by pasteboard: NSPasteboard) -> Bool {
        pasteboard.changeCount == changeCount
            && pasteboard.string(forType: Self.markerType) == marker
    }
}

/// Manual clipboard writes (catcher Copy, history Copy, snippet Copy
/// expansion). Copy is an explicit command, so it writes straight through —
/// the "Replace clipboard contents?" confirm was removed 2026-10-31 by
/// request. Oto's insertion path never uses this: it snapshots and restores
/// with receipts (below), so a dictation can still leave the prior clipboard
/// intact. Pure over an injected board, so tests use scratch boards and
/// never touch `.general`.
enum ClipboardWrite {
    nonisolated static func text(_ text: String, to board: NSPasteboard = .general) {
        board.clearContents()
        board.setString(text, forType: .string)
    }
}

/// Legacy name for the polish tests' injectable board (the manual clean-up
/// sheet that coined it is gone; the primitive is `ClipboardWrite`).
nonisolated func placePolishedOnClipboard(_ text: String, board: NSPasteboard = .general) {
    ClipboardWrite.text(text, to: board)
}

/// Full-fidelity clipboard snapshot: every type of every item, in order.
/// Pattern follows the Yap reference (`PasteboardSnapshot`, MIT) as Oto-owned
/// code. Pure over an injected pasteboard, so tests use a scratch board and
/// never touch `.general`.
enum PasteboardSnapshot {
    /// Hard total byte budget across all captured pasteboard representations.
    /// Prevents OOM and main-thread freezes on huge copied images or binary blobs.
    nonisolated static let maxTotalBytes = 20 * 1024 * 1024

    /// Promised-file and lazy file-promise pasteboard types that must never be
    /// materialized during a temporary snapshot (materializing can freeze the
    /// source app or break file promises on restore).
    nonisolated static let skippedTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("com.apple.pasteboard.promised-file-url"),
        NSPasteboard.PasteboardType("com.apple.pasteboard.promised-file-content-type"),
        NSPasteboard.PasteboardType("com.apple.NSFilePromiseItemMetaData"),
        NSPasteboard.PasteboardType("NSFilesPromisePboardType"),
    ]

    /// Carbon `kPasteboardFlavorSystemTranslated` bit (1 << 8): marks
    /// system-synthesized flavors (e.g. lazy TIFF/PDF conversions) that can
    /// be skipped whenever the item has at least one authoritative flavor
    /// (borrowed from Hex for faster, safer clipboard capture).
    nonisolated static let systemTranslatedFlag = PasteboardFlavorFlags(rawValue: 1 << 8)

    nonisolated static func shouldPreserveFlavor(
        flags: PasteboardFlavorFlags,
        hasAuthoritativeFlavor: Bool
    ) -> Bool {
        !hasAuthoritativeFlavor || !flags.contains(systemTranslatedFlag)
    }

    nonisolated static func capture(
        _ pasteboard: NSPasteboard,
        maxTotalBytes: Int = PasteboardSnapshot.maxTotalBytes
    ) -> [[NSPasteboard.PasteboardType: Data]] {
        if let carbonCaptured = captureViaCarbon(pasteboard, maxTotalBytes: maxTotalBytes) {
            return carbonCaptured
        }
        return captureViaAppKit(pasteboard, maxTotalBytes: maxTotalBytes)
    }

    /// Low-level Carbon Pasteboard capture: skips system-translated flavors
    /// when authoritative flavors exist on an item, avoiding expensive lazy
    /// image/PDF conversions on the main thread. Returns nil on API error so
    /// the caller falls back seamlessly to AppKit capture.
    private nonisolated static func captureViaCarbon(
        _ pasteboard: NSPasteboard,
        maxTotalBytes: Int
    ) -> [[NSPasteboard.PasteboardType: Data]]? {
        var pbRef: Pasteboard?
        let createStatus = PasteboardCreate(pasteboard.name.rawValue as CFString, &pbRef)
        guard createStatus == noErr, let ref = pbRef else { return nil }
        PasteboardSynchronize(ref)

        var itemCount: UInt = 0
        guard PasteboardGetItemCount(ref, &itemCount) == noErr else { return nil }
        guard itemCount > 0 else { return [] }

        var totalBytes = 0
        var captured: [[NSPasteboard.PasteboardType: Data]] = []
        for index in 1...Int(itemCount) {
            var itemID: PasteboardItemID?
            guard PasteboardGetItemIdentifier(ref, index, &itemID) == noErr,
                  let itemID
            else { continue }

            var flavorsRef: CFArray?
            guard PasteboardCopyItemFlavors(ref, itemID, &flavorsRef) == noErr,
                  let flavors = flavorsRef as? [String]
            else { continue }

            var entries: [(type: String, flags: PasteboardFlavorFlags)] = []
            entries.reserveCapacity(flavors.count)
            for flavor in flavors {
                var flags = PasteboardFlavorFlags()
                guard PasteboardGetItemFlavorFlags(ref, itemID, flavor as CFString, &flags) == noErr else {
                    continue
                }
                entries.append((flavor, flags))
            }

            let hasAuthoritative = entries.contains { !$0.flags.contains(systemTranslatedFlag) }
            var representation: [NSPasteboard.PasteboardType: Data] = [:]
            for entry in entries {
                let pbType = NSPasteboard.PasteboardType(entry.type)
                guard !skippedTypes.contains(pbType) else { continue }
                guard shouldPreserveFlavor(flags: entry.flags, hasAuthoritativeFlavor: hasAuthoritative) else {
                    continue
                }
                var dataRef: CFData?
                let status = PasteboardCopyItemFlavorData(ref, itemID, entry.type as CFString, &dataRef)
                guard status == noErr, let cfData = dataRef else {
                    continue
                }
                let data = cfData as Data
                guard totalBytes + data.count <= maxTotalBytes else { continue }
                totalBytes += data.count
                representation[pbType] = data
            }
            if !representation.isEmpty {
                captured.append(representation)
            }
        }
        return captured
    }

    private nonisolated static func captureViaAppKit(
        _ pasteboard: NSPasteboard,
        maxTotalBytes: Int
    ) -> [[NSPasteboard.PasteboardType: Data]] {
        var totalBytes = 0
        var captured: [[NSPasteboard.PasteboardType: Data]] = []
        for item in pasteboard.pasteboardItems ?? [] {
            var representation: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                guard !skippedTypes.contains(type) else { continue }
                guard let data = item.data(forType: type) else { continue }
                guard totalBytes + data.count <= maxTotalBytes else { continue }
                totalBytes += data.count
                representation[type] = data
            }
            if !representation.isEmpty {
                captured.append(representation)
            }
        }
        return captured
    }

    nonisolated static func restore(
        _ saved: [[NSPasteboard.PasteboardType: Data]],
        to pasteboard: NSPasteboard
    ) {
        pasteboard.clearContents()
        let nonEmpty = saved.filter { !$0.isEmpty }
        guard !nonEmpty.isEmpty else { return }
        let items = nonEmpty.enumerated().map { index, representation -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in representation {
                item.setData(data, forType: type)
            }
            if index == 0 {
                item.setData(Data(), forType: PasteboardReceipt.transientType)
            }
            return item
        }
        if !pasteboard.writeObjects(items) {
            log.error("clipboard restore failed after clearing — clipboard left empty")
        }
    }
}
